// Bundles @pierre/trees into the one file ui/vendor/trees.js, which the running agents and the definitions section views import, and
// writes the program icons of @lobehub/icons-static-svg as the symbols of ui/vendor/agent-icons.js (A32).
// --check builds the bundle again and fails when it differs from the committed files.
import { readFileSync, realpathSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { build } from "esbuild";

const OUTPUT = new URL("../ui/vendor/trees.js", import.meta.url);
const NOTICES = new URL("../ui/vendor/trees.LICENSE.txt", import.meta.url);
const ICONS = new URL("../ui/vendor/agent-icons.js", import.meta.url);
// The icon of each known agent CLI, by the program name that a row starts with, from the color icons of the library.
const ICON_FILES = { claude: "claude-color.svg", codex: "codex-color.svg", gemini: "gemini-color.svg" };
/* The licenses and notices of the bundled packages, which the release ships beside the bundle. */
const trees = dirname(realpathSync(new URL("../node_modules/@pierre/trees/package.json", import.meta.url)));
const preact = dirname(createRequire(join(trees, "package.json")).resolve("preact/package.json"));
const notices = [
  ["@pierre/trees 1.0.0-beta.4 (Apache-2.0)", join(trees, "LICENSE.md")],
  ["@pierre/trees NOTICE", join(trees, "NOTICE.md")],
  ["preact (MIT)", join(preact, "LICENSE")],
].map(([title, path]) => `# ${title}\n\n${readFileSync(path, "utf8").trim()}\n`).join("\n");
const result = await build({
  entryPoints: [new URL("../vendor/trees.js", import.meta.url).pathname],
  bundle: true,
  format: "esm",
  target: "safari17",
  legalComments: "eof",
  write: false,
  logLevel: "silent",
});
const bundled = result.outputFiles[0].text;
const lobe = dirname(realpathSync(new URL("../node_modules/@lobehub/icons-static-svg/package.json", import.meta.url)));
const lobeVersion = JSON.parse(readFileSync(join(lobe, "package.json"), "utf8")).version;
// Each icon becomes a symbol of its viewBox without its title, so a row draws it through <use>.
const symbols = Object.entries(ICON_FILES).map(([program, file]) => {
  const svg = readFileSync(join(lobe, "icons", file), "utf8");
  const viewBox = /viewBox="([^"]+)"/.exec(svg)?.[1];
  const body = /<svg[^>]*>([\s\S]*)<\/svg>/.exec(svg)?.[1]?.replace(/<title>[\s\S]*?<\/title>/, "");
  if (!viewBox || !body) throw new Error(`${file} of @lobehub/icons-static-svg is not an svg with a viewBox`);
  return [program, `<symbol id="soksak-agent-${program}" viewBox="${viewBox}">${body}</symbol>`];
});
const icons = `// Generated by scripts/build-vendor.mjs from @lobehub/icons-static-svg ${lobeVersion} (MIT, https://github.com/lobehub/lobe-icons).
// The symbol of the icon of each known agent CLI, by program name.
export const AGENT_ICON_SYMBOLS = ${JSON.stringify(Object.fromEntries(symbols), null, 2)};
`;
if (process.argv.includes("--check")) {
  for (const [file, text] of [[OUTPUT, bundled], [NOTICES, notices], [ICONS, icons]]) {
    if (readFileSync(file, "utf8") !== text) {
      console.error(`${file.pathname} differs from a new build; run pnpm build`);
      process.exit(1);
    }
  }
} else {
  writeFileSync(OUTPUT, bundled);
  writeFileSync(NOTICES, notices);
  writeFileSync(ICONS, icons);
}
